import random
from pathlib import Path

def create_test_files():
    """Создает тестовые файлы прямо в data/raw/"""
    
    # Базовая директория - теперь data/raw
    base_dir = Path('data/raw')
    
    # Папки для разных типов документов
    folders = ['доклады', 'журналы', 'конференции', 'обзоры', 'статьи']
    
